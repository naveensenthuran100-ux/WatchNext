def test_a_rejected_film_is_never_recommended_again():
    """The point of a thumbs-down: it has to stick."""
    import numpy as np
    from sklearn.preprocessing import normalize

    from src.signals import Signal
    from src.taste import fit_vectorizer, build_soup, recommend

    films = cache.all_movies()[:40]
    if len(films) < 20:
        pytest.skip("local cache too small for this test")

    weights = config.SOUP_WEIGHTS
    vectorizer, matrix = fit_vectorizer([build_soup(f, weights) for f in films])
    signal = Signal(normalize(np.asarray(matrix.todense(), dtype=np.float32)),
                    movies=list(films))
    signal.name = "metadata"

    seed = films[0]
    before = recommend(reference_features=[seed], signal=signal,
                       top_n=5, min_z=-10.0)
    assert before, "expected some picks to reject"

    rejected = before[0]
    feedback.record(USER, rejected["id"], -1)

    from src.recommender import build_profile
    after = recommend(profile=build_profile(None, USER),
                      reference_features=[seed], signal=signal,
                      top_n=5, min_z=-10.0)
    assert rejected["id"] not in [p["id"] for p in after]
