def test_vote_buttons_fit_telegrams_callback_limit():
    from src.bot import _vote_keyboard

    keyboard = _vote_keyboard([
        {"id": 157336, "title": "Interstellar"},
        {"id": 286217, "title": "A Very Long Film Title That Goes On And On"},
    ])
    buttons = [b for row in keyboard.inline_keyboard for b in row]
    assert len(buttons) == 4
    for button in buttons:
        assert len(button.callback_data.encode()) <= 64


def test_vote_buttons_are_skipped_for_films_with_no_id():
    from src.bot import _vote_keyboard

    assert _vote_keyboard([{"title": "No Id Here"}]) is None


def test_vote_callback_data_round_trips():
    from src.bot import VOTE_PREFIX, _vote_keyboard

    keyboard = _vote_keyboard([{"id": 999, "title": "X"}])
    up, down = keyboard.inline_keyboard[0]
    for button, expected in ((up, 1), (down, -1)):
        prefix, verdict, movie_id = button.callback_data.split(":")
        assert prefix == VOTE_PREFIX
        assert int(verdict) == expected
        assert int(movie_id) == 999


