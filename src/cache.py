def get_cached_profile(username: str, max_age: float = None) -> dict | None:
    """A previously scraped profile, if it is still fresh enough."""
    max_age = config.PROFILE_TTL if max_age is None else max_age
    with _lock:
        row = _conn.execute(
            "SELECT data, fetched_at FROM profiles WHERE username = ?",
            (username.lower().strip(),),
        ).fetchone()
    if not row or (time.time() - row[1]) > max_age:
        return None

    profile = json.loads(row[0])
    # watched_keys round-trips through JSON as a list of pairs.
    profile["watched_keys"] = {tuple(k) for k in profile.get("watched_keys", [])}
    return profile


def put_profile(username: str, profile: dict) -> None:
    serialisable = dict(profile)
    serialisable["watched_keys"] = [list(k) for k in profile.get("watched_keys", set())]
    with _lock:
        _conn.execute(
            "INSERT OR REPLACE INTO profiles (username, data, fetched_at) VALUES (?, ?, ?)",
            (username.lower().strip(), json.dumps(serialisable), time.time()),
        )
        _conn.commit()


def get_recommendations(movie_id: int) -> list | None:
    with _lock:
        row = _conn.execute(
            "SELECT rec_ids FROM recommendations WHERE movie_id = ?",
            (int(movie_id),)).fetchone()
    return json.loads(row[0]) if row else None


def put_recommendations(movie_id: int, rec_ids: list) -> None:
    with _lock:
        _conn.execute(
            "INSERT OR REPLACE INTO recommendations (movie_id, rec_ids, fetched_at) "
            "VALUES (?, ?, ?)",
            (int(movie_id), json.dumps([int(r) for r in rec_ids]), time.time()))
        _conn.commit()


def all_recommendations() -> dict:
    with _lock:
        rows = _conn.execute("SELECT movie_id, rec_ids FROM recommendations").fetchall()
    return {int(r[0]): json.loads(r[1]) for r in rows}


