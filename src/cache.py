def put_feedback(user_id: str, movie_id: int, verdict: int) -> None:
    """Record a thumbs up (+1) or down (-1). Re-voting replaces."""
    with _lock:
        _conn.execute(
            "INSERT OR REPLACE INTO feedback "
            "(user_id, movie_id, verdict, created_at) VALUES (?, ?, ?, ?)",
            (str(user_id), int(movie_id), int(verdict), time.time()))
        _conn.commit()


def get_feedback(user_id: str) -> dict:
    """movie_id -> verdict for one user."""
    with _lock:
        rows = _conn.execute(
            "SELECT movie_id, verdict FROM feedback WHERE user_id = ?",
            (str(user_id),)).fetchall()
    return {int(r[0]): int(r[1]) for r in rows}


def feedback_counts(user_id: str) -> tuple[int, int]:
    votes = get_feedback(user_id)
    up = sum(1 for v in votes.values() if v > 0)
    return up, len(votes) - up


def profile_age(username: str) -> float | None:
    """Seconds since this profile was scraped, or None if never."""
    with _lock:
        row = _conn.execute(
            "SELECT fetched_at FROM profiles WHERE username = ?",
            (username.lower().strip(),),
        ).fetchone()
    return (time.time() - row[0]) if row else None
